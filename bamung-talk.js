//  · 대화 하나는 [ ] 안에 한 줄씩 따옴표로 적는다. 줄끼리는 쉼표로 띄운다.
//  · 묶음마다 누가 먼저 말하는지 정해져 있다 (묶음 위 설명). 그다음부터는 번갈아 말한다.
